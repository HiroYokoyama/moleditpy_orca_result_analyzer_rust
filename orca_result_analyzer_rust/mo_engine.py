MAX_SUPPORTED_L = 4

class BasisSetEngine:
    """
    GTO-based Basis Set evaluator backed by the Rust extension.
    Accepts the same shell dicts as the original Python implementation.
    """

    def __init__(self, shells):
        """
        shells: list of dicts — each:
          {'type': int, 'center': [x,y,z] Bohr, 'exps': array, 'coeffs': array}
        """
        for sh in shells:
            l_type = int(sh["type"])
            if not 0 <= l_type <= MAX_SUPPORTED_L:
                # Skipping such a shell would leave every later shell reading
                # the wrong slice of the MO coefficient vector — a silently
                # wrong orbital with nothing on screen to say so.
                letter = (
                    SHELL_LETTERS[l_type]
                    if 0 <= l_type < len(SHELL_LETTERS)
                    else f"l={l_type}"
                )
                raise UnsupportedBasisError(
                    f"This basis set contains {letter} shells, which the "
                    "orbital renderer does not support (S through G only)."
                    "\n\nVisualization is blocked rather than showing an "
                    "orbital that would be silently incorrect."
                )

        self.shells = [dict(shell) for shell in shells]
        offset = 0
        for shell in self.shells:
            shell["start_idx"] = offset
            offset += 2 * int(shell["type"]) + 1
        rust_shells = [
            {
                "type": int(sh["type"]),
                "center": [float(v) for v in sh["center"]],
                "exps": [float(v) for v in sh["exps"]],
                "coeffs": [float(v) for v in sh["coeffs"]],
            }
            for sh in shells
        ]
        self._engine = _rs.BasisSetEngineRust(rust_shells)
        self.n_basis = self._engine.n_basis

    def _normalization_prefactor(self, alpha, l, m, n):  # noqa: E741
        L = l + m + n
        fact = {0: 1, 1: 1, 2: 2, 3: 6, 4: 24, 5: 120}
        fact2 = {0: 1, 1: 2, 2: 24, 3: 720, 4: 40320, 5: 3628800}

        num = (8 * alpha) ** L * fact[l] * fact[m] * fact[n]
        den = fact2[l] * fact2[m] * fact2[n]
        return ((2 * alpha / np.pi) ** 0.75) * np.sqrt(num / den)

    def evaluate_mo_on_grid(self, mo_idx, grid_coords, mo_coeffs_all):
        """
        Evaluate MO on grid.
        mo_coeffs_all: 1D array of all MO coefficients (must match n_basis)
        grid_coords: (N, 3) array in Bohr
        Returns (N,) numpy array of phi values.
        """
        grid_coords = np.asarray(grid_coords, dtype=float)
        if grid_coords.ndim != 2 or grid_coords.shape[1] != 3:
            raise ValueError("Grid coordinates must have shape (N, 3).")
        if len(mo_coeffs_all) != self.n_basis:
            raise ValueError(
                f"Expected {self.n_basis} coefficients, got {len(mo_coeffs_all)}"
            )
        grid_flat = grid_coords.ravel().tolist()
        result = self._engine.evaluate_mo_on_grid(grid_flat, list(mo_coeffs_all))
        return np.array(result)


class CalcWorker(QThread):
    """Background thread that evaluates one MO on a grid and writes its cube file."""

    progress_sig = Signal(int)
    finished_sig = Signal(bool, str)

    def __init__(
        self,
        engine,
        mo_idx,
        n_points,
        margin,
        atoms_sym,
        atoms_coords,
        mo_coeffs,
        output_path,
    ):
        super().__init__()
        self.engine = engine
        self.mo_idx = mo_idx
        self.n_points = n_points  # grid points per axis
        self.margin = margin  # in Angstrom
        self.atoms_sym = atoms_sym
        self.atoms_coords = atoms_coords  # Angstrom
        self.mo_coeffs = mo_coeffs
        self.output_path = output_path
        self._is_cancelled = False

    def cancel(self) -> None:
        """Ask the worker to stop at the next grid chunk; it then emits finished_sig(False, CANCELLED)."""
        self._is_cancelled = True

    def run(self):
        """Evaluate the orbital on its grid and write the resulting cube file."""
        try:
            # Guard: with a single grid point per axis span/(n-1) divides by
            # zero, which numpy turns into inf spacing and a silently corrupt
            # cube file instead of an exception.
            if self.n_points < 2:
                self.finished_sig.emit(
                    False, "Grid resolution must be at least 2 points per axis."
                )
                return

            BOHR_TO_ANG = 0.529177249
            ANG_TO_BOHR = 1.0 / BOHR_TO_ANG

            # Define Grid in BOHR (Engine expects Bohr)
            coords_bohr = np.array(self.atoms_coords) * ANG_TO_BOHR
            margin_bohr = self.margin * ANG_TO_BOHR

            min_c = np.min(coords_bohr, axis=0) - margin_bohr
            max_c = np.max(coords_bohr, axis=0) + margin_bohr
            span = max_c - min_c

            nx = ny = nz = self.n_points
            dx = span[0] / (nx - 1)
            dy = span[1] / (ny - 1)
            dz = span[2] / (nz - 1)

            x = np.linspace(min_c[0], max_c[0], nx)
            y = np.linspace(min_c[1], max_c[1], ny)
            z = np.linspace(min_c[2], max_c[2], nz)

            X, Y, Z = np.meshgrid(x, y, z, indexing="ij")
            grid_points = np.column_stack([X.ravel(), Y.ravel(), Z.ravel()])

            n_total = grid_points.shape[0]
            chunk_size = 50000
            result_flat = np.zeros(n_total)

            for start in range(0, n_total, chunk_size):
                if self._is_cancelled:
                    # Still report back, or the dialog's queue never advances.
                    self.finished_sig.emit(False, CANCELLED)
                    return
                end = min(start + chunk_size, n_total)
                chunk_pts = grid_points[start:end]

                val = self.engine.evaluate_mo_on_grid(
                    self.mo_idx, chunk_pts, self.mo_coeffs
                )
                result_flat[start:end] = val

                pct = int((end / n_total) * 100)
                self.progress_sig.emit(pct)

            # Write Cube
            vol_data = result_flat.reshape(nx, ny, nz)  # pylint: disable=too-many-function-args
            vectors = np.diag([dx, dy, dz])

            # Safe handling of mo_idx for comment
            # Convert 0-based to 1-based if numeric, including "0_alpha" -> "1_alpha"
            mo_display_id = str(self.mo_idx)
            try:
                if "_" in str(self.mo_idx):
                    parts = str(self.mo_idx).split("_")
                    if parts[0].isdigit():
                        parts[0] = str(int(parts[0]) + 1)
                        mo_display_id = "_".join(parts)
                else:
                    mo_display_id = str(int(self.mo_idx) + 1)
            except (IndexError, TypeError, ValueError):
                # Fallback to original string
                logging.debug(
                    "MO display id formatting failed; using raw value", exc_info=True
                )

            CubeWriter.write(
                self.output_path,
                self.atoms_sym,
                self.atoms_coords,
                min_c,
                vectors,
                vol_data,
                comment=f"MO {mo_display_id}",
                grid_points=self.n_points,
                margin=self.margin,
            )

            self.finished_sig.emit(True, self.output_path)

        # worker-thread top level: an escaping exception would kill the thread silently
        except Exception as e:  # pylint: disable=broad-exception-caught
            logging.exception("MO: cube generation failed for MO %s", self.mo_idx)
            self.finished_sig.emit(False, str(e))
