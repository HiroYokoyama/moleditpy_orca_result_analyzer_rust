import os
import logging
import re
import numpy as np
from PySide6.QtCore import QThread, Signal

try:
    from . import PLUGIN_VERSION
except ImportError:  # module loaded flat (test harness / Rust port)
    PLUGIN_VERSION = "unknown"

#: Shell letters ORCA can print, indexed by angular momentum.
SHELL_LETTERS = "SPDFGHIK"

#: finished_sig message for a worker stopped by CalcWorker.cancel().
CANCELLED = "Cancelled"


class UnsupportedBasisError(ValueError):
    """The basis set uses shells this engine cannot evaluate exactly.

    Raised instead of rendering a partial or mis-indexed orbital — the
    message is written for the user and shown verbatim in the dialog.
    """


def read_generation_settings(filepath):
    """What a cube on disk was generated with.

    Returns a dict with "version", "grid" and "margin"; any value the file
    does not record (older cubes, or one written by another program) comes
    back as None so the caller can say "unknown" rather than guess.
    """
    info = {"version": None, "grid": None, "margin": None}
    try:
        with open(filepath, "r", encoding="utf-8", errors="replace") as fh:
            fh.readline()  # line 1: "ORCA Analyzer Cube File: MO n"
            stamp = fh.readline()
    except OSError as e:
        logging.warning("Could not read cube header %s: %s", filepath, e)
        return info

    m = re.search(r"ORCA Result Analyzer v(\S+)", stamp)
    if m:
        info["version"] = m.group(1)
    m = re.search(r"grid=(\d+)", stamp)
    if m:
        info["grid"] = int(m.group(1))
    m = re.search(r"margin=([0-9.]+)", stamp)
    if m:
        try:
            info["margin"] = float(m.group(1))
        except ValueError:
            logging.warning("Unparsable margin in %s", filepath)
    return info


class CubeWriter:
    """Writes a Gaussian-cube file for a computed MO grid."""

    @staticmethod
    def write(
        filepath,
        atoms_sym,
        atoms_coords,
        origin,
        vectors,
        data,
        comment="",
        grid_points=None,
        margin=None,
    ):
        """
        Write a .cube file.
        atoms_sym: list of atomic symbols (str) or atomic numbers (int)
        atoms_coords: list/array of (x,y,z) in Angstrom
        origin: (x,y,z) of grid origin in Bohr
        vectors: 3x3 array of grid vectors in Bohr
        data: 3D numpy array of values
        """
        # Ensure directory exists
        dirname = os.path.dirname(filepath)
        if dirname and not os.path.exists(dirname):
            try:
                os.makedirs(dirname, exist_ok=True)
            except OSError as e:
                logging.warning("Error creating directory %s: %s", dirname, e)

        nx, ny, nz = data.shape
        n_atoms = len(atoms_sym)

        # Periodic Table for Atomic Number lookup if symbols provided
        try:
            from rdkit import Chem

            try:
                from .utils import normalize_atom_symbol
            except ImportError:  # module loaded flat (test harness)
                from utils import normalize_atom_symbol

            pt = Chem.GetPeriodicTable()

            def to_z(s):
                # Ghost/dummy labels ("X", "DA", "H:") made GetAtomicNumber
                # raise and failed the whole cube; they are Z=0 in a cube.
                if not isinstance(s, str):
                    return int(s)
                sym = normalize_atom_symbol(s)
                if sym == "*":
                    return 0
                try:
                    return pt.GetAtomicNumber(sym)
                except RuntimeError:
                    # RDKit's "Element not found" post-condition violation.
                    return 0
        except (ImportError, AttributeError, RuntimeError):
            # Fallback simple map if RDKit fails (unlikely)
            def to_z(s):
                return 0 if isinstance(s, str) else int(s)

        with open(filepath, "w", encoding="utf-8") as f:
            f.write(f"ORCA Analyzer Cube File: {comment}\n")
            # Stamp the generating version: the f/g normalization fix in
            # 3.12.0 changed the values in every cube containing those
            # shells, so a file's provenance has to be readable from the
            # file itself.
            # The cube format allows exactly two comment lines, so the
            # generation settings ride along on this one rather than adding a
            # third. read_generation_settings() parses them back out.
            stamp = f"Generated by MoleditPy ORCA Result Analyzer v{PLUGIN_VERSION}"
            if grid_points is not None:
                stamp += f" | grid={int(grid_points)}"
            if margin is not None:
                stamp += f" | margin={float(margin):.2f}"
            f.write(stamp + "\n")
            # Cube file format requires atomic coordinates in Bohr if origin/vectors are in Bohr
            # Actually, standard Cube usually defines:
            # - Number of Atoms, Origin (X,Y,Z)
            # - NX, X-Vector
            # - NY, Y-Vector
            # - NZ, Z-Vector
            # - Atom 1: Z, Charge, X, Y, Z
            # ...
            # Volumetric Data

            # Note: Gaussian Cube uses Bohr for units usually.
            # Our atoms_coords are usually Angstroms from parser.
            BOHR_TO_ANG = 0.529177249
            ANG_TO_BOHR = 1.0 / BOHR_TO_ANG

            # Convert units to Bohr for the file
            origin_bohr = origin  # Assumed passed in Bohr
            vectors_bohr = vectors  # Assumed passed in Bohr
            coords_bohr = np.array(atoms_coords) * ANG_TO_BOHR

            f.write(
                f"{n_atoms:5d} {origin_bohr[0]:12.6f} {origin_bohr[1]:12.6f} {origin_bohr[2]:12.6f}\n"
            )
            f.write(
                f"{nx:5d} {vectors_bohr[0, 0]:12.6f} {vectors_bohr[0, 1]:12.6f} {vectors_bohr[0, 2]:12.6f}\n"
            )
            f.write(
                f"{ny:5d} {vectors_bohr[1, 0]:12.6f} {vectors_bohr[1, 1]:12.6f} {vectors_bohr[1, 2]:12.6f}\n"
            )
            f.write(
                f"{nz:5d} {vectors_bohr[2, 0]:12.6f} {vectors_bohr[2, 1]:12.6f} {vectors_bohr[2, 2]:12.6f}\n"
            )

            for i in range(n_atoms):
                z_no = to_z(atoms_sym[i])
                # Cube format: Z, Charge(float), X, Y, Z (Bohr)
                f.write(
                    f"{z_no:5d} {float(z_no):12.6f} {coords_bohr[i][0]:12.6f} {coords_bohr[i][1]:12.6f} {coords_bohr[i][2]:12.6f}\n"
                )

            vals = data.flatten()
            for i, v in enumerate(vals):
                f.write(f"{v:13.5E}")
                if (i + 1) % 6 == 0:
                    f.write("\n")
            if len(vals) % 6 != 0:
                f.write("\n")


