"""Independent radial integrals, signed harmonic values and spin-to-cube checks.

References: SciPy's normalized sph_harm_y (Condon--Shortley convention),
https://docs.scipy.org/doc/scipy/reference/generated/scipy.special.sph_harm_y.html
and the closed-form Gaussian integral integral(exp(-p*r*r), R) = sqrt(pi/p).
No angular polynomial or normalization helper from the engine is reused.
The repository's benzene cubes were generated by this plugin, so they are
regression fixtures, NOT independent ORCA cube references.
"""

import math
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import Mock

import numpy as np
import pytest

from ._parser_loader import load_standalone_parser
from .test_mo_engine import _mod as engine_module

Engine = engine_module.BasisSetEngine


def shell(degree, exponents=(0.8,), coefficients=(1.0,), center=(0.0, 0.0, 0.0)):
    return {
        "type": degree,
        "center": np.array(center),
        "exps": np.array(exponents),
        "coeffs": np.array(coefficients),
    }


@pytest.mark.parametrize("degree", range(5))
@pytest.mark.parametrize("alpha", [0.4, 1.3, 2.8])
def test_absolute_signed_components_match_independent_spherical_harmonics(
    degree, alpha
):
    special = pytest.importorskip("scipy.special")
    directions = np.array(
        [[0.2, 0.3, 0.5], [-0.3, 0.8, -0.2], [0.9, -0.4, 0.6], [-0.5, -0.4, -0.3]]
    )
    directions /= np.linalg.norm(directions, axis=1)[:, None]
    local = (directions[:, None, :] * np.array([0.2, 0.9, 1.8])[None, :, None]).reshape(
        -1, 3
    )
    center = np.array([0.7, -0.4, 0.2])
    radius = np.linalg.norm(local, axis=1)
    theta = np.arccos(local[:, 2] / radius)
    phi = np.arctan2(local[:, 1], local[:, 0])
    # Integral r**(2*l+2)*exp(-2*a*r*r) dr = Gamma(l+3/2)/(2*(2*a)**(l+3/2)).
    radial = math.sqrt(2 * (2 * alpha) ** (degree + 1.5) / math.gamma(degree + 1.5))
    radial = radial * radius**degree * np.exp(-alpha * radius**2)
    engine = Engine([shell(degree, (alpha,), center=center)])
    orders = [0] + [m for i in range(1, degree + 1) for m in (i, -i)]
    for component, order in enumerate(orders):
        if hasattr(special, "sph_harm_y"):
            harmonic = special.sph_harm_y(degree, abs(order), theta, phi)
        else:
            # Older SciPy uses (order, degree, azimuth, polar), same phase.
            harmonic = special.sph_harm(abs(order), degree, phi, theta)
        if order:
            harmonic = (
                math.sqrt(2)
                * (-1) ** abs(order)
                * (harmonic.real if order > 0 else harmonic.imag)
            )
        else:
            harmonic = harmonic.real
        coefficients = np.eye(2 * degree + 1)[component]
        actual = engine.evaluate_mo_on_grid(0, local + center, coefficients)
        # The legacy d(+2) table rounds sqrt(3)/2 to six decimals.
        np.testing.assert_allclose(actual, radial * harmonic, rtol=8e-7, atol=2e-12)


@pytest.mark.parametrize("degree", range(5))
def test_signed_contraction_norm_matches_closed_form_radial_overlap(degree):
    exponents = (0.8, 1.1)
    coefficients = (0.8, -0.25)
    center = np.array([0.3, -0.8, 1.2])
    engine = Engine([shell(degree, exponents, coefficients, center)])
    # Independent overlap of normalized, same-center, same-(l,m) primitives.
    expected = sum(
        c * d * (2 * math.sqrt(a * b) / (a + b)) ** (degree + 1.5)
        for a, c in zip(exponents, coefficients)
        for b, d in zip(exponents, coefficients)
    )
    nodes, weights = np.polynomial.hermite.hermgauss(18)
    xyz = np.stack(np.meshgrid(nodes, nodes, nodes, indexing="ij"), axis=-1).reshape(
        -1, 3
    )
    tensor_weights = np.prod(
        np.stack(np.meshgrid(weights, weights, weights, indexing="ij"), axis=-1),
        axis=-1,
    ).ravel()
    scale = math.sqrt(2 * min(exponents))
    integration_weights = tensor_weights * np.exp(np.sum(xyz**2, axis=1)) / scale**3
    for vector in np.eye(2 * degree + 1):
        values = engine.evaluate_mo_on_grid(0, center + xyz / scale, vector)
        # Squaring the rounded d(+2) prefactor doubles its relative error.
        assert np.dot(values**2, integration_weights) == pytest.approx(
            expected, rel=1.1e-6, abs=1e-11
        )


