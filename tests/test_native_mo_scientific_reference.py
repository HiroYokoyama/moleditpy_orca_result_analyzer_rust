def test_external_orca_output_preserves_geometry_energy_pairs_and_atom_order():
    # Public tracked ORCA fixture; licensing/provenance: sample_outputs/NOTICE.
    # Manually transcribed, one-based source lines (not another parser's output):
    # cycle1: coordinates276-277, energy1383; cycle4: coordinates2467-2468, energy2804.
    source = Path(__file__).parent / "sample_outputs" / "o2-opt_orb.out"
    parser = load_standalone_parser("external_geometry_energy").OrcaParser()
    parser.load_from_memory(source.read_text(encoding="utf-8"), str(source))
    cycles = {
        step["step"]: step
        for step in parser.data["scan_steps"]
        if step["type"] == "opt_cycle"
    }
    for cycle, x, energy in [
        (1, 0.575465, -150.049852306840),
        (4, 0.594111, -150.052452178414),
    ]:
        assert cycles[cycle]["atoms"] == ["O", "O"]
        np.testing.assert_allclose(
            cycles[cycle]["coords"], [[x, 0.0, 0.0], [-x, 0.0, 0.0]], rtol=0, atol=5e-12
        )
        # The parser exposes the later Current Energy summary (nine decimals).
        # FINAL SINGLE POINT ENERGY above is the independent, finer oracle;
        # allow only half one unit of that summary's last decimal plus FP noise.
        assert cycles[cycle]["energy"] == pytest.approx(energy, rel=0, abs=5.1e-10)


def _read_generated_cube(path):
    lines = path.read_text(encoding="utf-8").splitlines()
    atom_count = int(lines[2].split()[0])
    origin = np.array([float(x) for x in lines[2].split()[1:]])
    dims = tuple(int(lines[i].split()[0]) for i in (3, 4, 5))
    vectors = np.array([[float(x) for x in lines[i].split()[1:]] for i in (3, 4, 5)])
    indices = np.indices(dims).reshape(3, -1).T
    values = np.array(
        [float(x) for row in lines[6 + atom_count :] for x in row.split()]
    )
    return origin + indices @ vectors, values


@pytest.mark.parametrize("spin,center_x,sign", [("alpha", 0.0, 1), ("beta", 0.8, -1)])
def test_uhf_dialog_selection_reaches_the_correct_signed_gaussian_cube(
    spin, center_x, sign, tmp_path, monkeypatch
):
    from . import gui_harness

    parser = load_standalone_parser("scientific_reference").OrcaParser()
    parser.load_from_memory(_unrestricted_output(), str(tmp_path / "synthetic.out"))
    module = gui_harness.load_isolated("mo_analysis")
    monkeypatch.setattr(module, "__file__", str(tmp_path / "mo_analysis.py"))
    monkeypatch.setattr(module, "BasisSetEngine", Engine)
    monkeypatch.setattr(module, "connect_queued", lambda *args, **kwargs: None)
    workers = []

    def make_worker(*args):
        worker = engine_module.CalcWorker(*args)
        worker.finished_sig = Mock()
        worker.progress_sig = Mock()
        worker.finished = Mock()
        worker.start = Mock()
        workers.append(worker)
        return worker

    monkeypatch.setattr(module, "CalcWorker", make_worker)
    host = SimpleNamespace(parser=parser, file_path=parser.filename, context=Mock())
    dialog = module.MODialog(host, parser.data["mo_coeffs"], result_dir=str(tmp_path))
    dialog.spin_pts.setValue(10)
    dialog.spin_margin.setValue(1.0)
    dialog.generation_silent = True
    dialog._generate_single_mo(f"0_{spin}")
    assert len(workers) == 1
    worker = workers[0]
    try:
        worker.run()
        assert worker.finished_sig.emit.call_args.args[0] is True
        grid, actual = _read_generated_cube(Path(worker.output_path))
        displacement = grid - np.array([center_x / 0.529177249, 0.0, 0.0])
        expected = (
            sign
            * (1.6 / math.pi) ** 0.75
            * np.exp(-0.8 * np.sum(displacement**2, axis=1))
        )
        # Header coordinates have six decimals, values six significant digits.
        np.testing.assert_allclose(actual, expected, rtol=3e-5, atol=2e-8)
    finally:
        module._RUNNING_WORKERS.discard(worker)
